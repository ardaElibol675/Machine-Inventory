"""git repositories under the repo_scan roots.

snapshot/repos.tsv       path(~) remote branch uncommitted unpushed   (machine-readable)
snapshot/repos.md        the same as a table
snapshot/dirty-repos.md  `git status --porcelain` of every repo with uncommitted files
"""
import fnmatch
import os

from .. import shell
from ..config import expand, tilde
from .base import PHASE_REPOS, Step, q, read_lines, missing_items


def find_repos(ctx):
    scan = ctx.cfg["repo_scan"]
    excludes = list(scan.get("exclude") or [])
    skip_roots = {str(ctx.tool_root), str(ctx.data)}
    found = set()
    for root in scan.get("roots") or ["~"]:
        root = str(expand(root))
        base_depth = root.rstrip("/").count("/")
        for cur, dirs, _ in os.walk(root, onerror=lambda e: None):
            depth = cur.rstrip("/").count("/") - base_depth
            if ".git" in dirs:
                git = os.path.join(cur, ".git")
                if (depth + 1 <= scan.get("depth", 5)
                        and not any(fnmatch.fnmatch(git, e) for e in excludes)
                        and not any(cur == s or cur.startswith(s + "/") for s in skip_roots)):
                    found.add(cur)
            dirs[:] = [d for d in dirs if d != ".git" and depth + 1 < scan.get("depth", 5)
                       and not os.path.islink(os.path.join(cur, d))]
    return sorted(found)


def _git(path, *args):
    return shell.run(["git", "-C", path, *args], check=False)


def collect(ctx, snap):
    if not shell.have("git"):
        return
    rows, dirty = [], []
    for d in find_repos(ctx):
        remote = (_git(d, "remote", "get-url", "origin") or "-").strip()
        branch = (_git(d, "branch", "--show-current") or "").strip() or "(detached)"
        status = (_git(d, "status", "--porcelain") or "").rstrip("\n")
        n = len([l for l in status.splitlines() if l])
        ahead = _git(d, "rev-list", "--count", "@{u}..HEAD")
        ahead = ahead.strip() if ahead is not None else "?"
        rows.append([tilde(d), remote, branch, str(n), ahead])
        if status:
            dirty.append((tilde(d), remote, status))

    snap.write_lines("repos.tsv", ["\t".join(r) for r in rows])
    md = ["# git repositories", "", "Generated by `mi export`. Do not edit.", "",
          "| Path | Remote | Branch | Uncommitted | Unpushed |", "|---|---|---|---|---|"]
    md += [f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} |" for r in rows]
    snap.write_lines("repos.md", md)
    out = ["# Uncommitted changes", "", "Generated by `mi export`. Report only; nothing is committed or pushed.",
           "Status codes: `M` modified, `D` deleted, `??` untracked."]
    for path, remote, status in dirty:
        out += ["", f"## `{path}`", f"Remote: {remote}", "", "```", status, "```"]
    snap.write_lines("dirty-repos.md", out)


def repos(ctx):
    out = []
    for line in read_lines(ctx.snapshot / "repos.tsv"):
        f = line.split("\t")
        if len(f) == 5:
            out.append(dict(zip(("path", "remote", "branch", "dirty", "ahead"), f)))
    return out


def check(ctx, rep):
    rep.section("git repositories")
    clean = True
    for r in repos(ctx):
        if r["dirty"] != "0":
            clean = False
            rep.warn(f"repo: {r['path']} has {r['dirty']} uncommitted files")
        if r["ahead"] == "?":
            clean = False
            rep.warn(f"repo: {r['path']} has no upstream branch")
        elif r["ahead"] != "0":
            clean = False
            rep.warn(f"repo: {r['path']} has {r['ahead']} unpushed commits")
    if clean:
        rep.ok("repos: everything committed and pushed (as of the last export)")


def drift(ctx, catalog, rep):
    claimed = catalog.claimed("repos")
    unclaimed = [r["path"] for r in repos(ctx) if r["path"] not in claimed]
    if unclaimed:
        rep.warn(f"repos: uncatalogued: {' '.join(unclaimed)}")
    else:
        rep.ok("repos: every repository is catalogued")
    have = {r["path"] for r in repos(ctx)}
    missing_items(ctx, catalog, rep, "repos", lambda p: p in have, "repos", " (not cloned here)")


def steps(ctx, catalog, items):
    known = {r["path"]: r for r in repos(ctx)}
    cmds, notes = [], []
    for i in items:
        for path in i.get("repos"):
            r = known.get(path)
            if not r or r["remote"] == "-":
                notes.append(f"{path}: no remote in the snapshot; skipped")
                continue
            dst = expand(path)
            b = f"-b {q(r['branch'])} " if r["branch"] != "(detached)" else ""
            cmds.append(f"[ -e {q(dst / '.git')} ] && echo 'exists: {dst}' || "
                        f"git clone {b}{q(r['remote'])} {q(dst)}")
    if not (cmds or notes):
        return []
    return [Step(PHASE_REPOS, "git repositories (needs your SSH key on the git host for ssh remotes)", cmds, notes)]
