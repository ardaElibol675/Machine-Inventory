"""catalog.yaml -> INVENTORY.md (human-readable, generated, never edited by hand).

In a migration target the file also gets the target system and a table of the
migration decisions (migration.yaml)."""
from .catalog import LIST_KEYS
from .config import read_os_release

SHOWN = [k for k in LIST_KEYS if k not in ("post",)]


def _compat(item):
    parts = [f"{d} {', '.join(v) if v else '(any)'}" for d, v in item.compat.items()]
    parts += [f"needs {p}" for p in item.requires_paths]
    return _cell("; ".join(parts)) or "any"


def _cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def _summary(item):
    parts = [f"{k} ({len(item.get(k))})" for k in SHOWN if item.get(k)]
    if item.manual:
        parts.append("manual")
    return ", ".join(parts) or "-"


def _details(item):
    out = []
    if item.replaces:
        out.append("  - replaces: " + ", ".join(f"`{v}`" for v in item.replaces))
    for k in SHOWN + ["post"]:
        if item.get(k):
            out.append(f"  - {k}: " + ", ".join(f"`{v}`" for v in item.get(k)))
    if item.manual:
        out.append("  - manual: " + _cell(item.manual))
    if item.notes:
        out.append("  - notes: " + _cell(item.notes))
    return out


def _decisions(migration):
    decisions = migration.get("decisions") or {}
    out = ["", '<a id="decisions"></a>', "## Migration decisions", "",
           "One row per inventory item (and per item added for this target), from `migration.yaml`.", "",
           "| Item | Decision | By | Why | Todo |", "|---|---|---|---|---|"]
    for iid, d in decisions.items():
        d = d or {}
        by = ", ".join(f"`{b}`" for b in d.get("by") or []) or "-"
        out.append(f"| `{iid}` | {d.get('action', '?')} | {by} | {_cell(d.get('why') or '') or '-'} | "
                   f"{_cell(d.get('todo') or '') or '-'} |")
    counts = {}
    for d in decisions.values():
        a = (d or {}).get("action", "?")
        counts[a] = counts.get(a, 0) + 1
    out += ["", "Totals: " + ", ".join(f"{a} {n}" for a, n in sorted(counts.items())) if counts else ""]
    todos = [(iid, d["todo"]) for iid, d in decisions.items() if d and d.get("todo")]
    if todos:
        out += ["", "### Manual follow-up", ""] + [f"- `{iid}`: {_cell(t)}" for iid, t in todos]
    return out


def render(catalog, snapshot_dir, migration=None):
    system = read_os_release(snapshot_dir / "system.txt") if (snapshot_dir / "system.txt").exists() else {}
    if migration:
        target = migration.get("target") or {}
        source = migration.get("source") or {}
        out = [f"# Migration target: {target.get('PRETTY_NAME') or target.get('ID', '?')}", "",
               "Generated from `catalog.yaml` and `migration.yaml` by `mi render`. Do not edit this file.", "",
               f"**Target:** {target.get('PRETTY_NAME', '?')} ({target.get('ID', '?')} "
               f"{target.get('VERSION_ID', '?')}, {target.get('VERSION_CODENAME') or 'no codename'})  ",
               f"**Migrated from:** {source.get('system') or '?'}, inventory commit "
               f"`{source.get('inventory_commit') or 'unknown'}`, created {source.get('created') or '?'}"]
        out += _decisions(migration)
        out.append("")
    else:
        out = ["# Machine inventory", "",
               "Generated from `catalog.yaml` by `mi render`. Do not edit this file: change `catalog.yaml`, "
               "then run `mi render`.", ""]
    if system:
        out += [f"**Snapshot of:** {system.get('PRETTY_NAME', '?')}, kernel {system.get('KERNEL', '?')}", ""]
    out += ["**Default** = pre-ticked in `mi restore`. **Compat** = systems the item was tested on.", "",
            "## Groups", ""]
    out += [f"- [{g.name}](#{g.id}) ({len(g.items)})" for g in catalog.groups]
    if catalog.known:
        out.append(f"- [Known, not restored](#known) ({len(catalog.known)})")

    for g in catalog.groups:
        out += ["", f'<a id="{g.id}"></a>', f"## {g.name}", "",
                "| Item | Name | Installs | Why | Default | Compat |", "|---|---|---|---|---|---|"]
        for i in g.items:
            out.append(f"| `{i.id}` | {_cell(i.name)} | {_summary(i)} | {_cell(i.why) or '-'} | "
                       f"{'yes' if i.default else 'no'} | {_compat(i)} |")
        out.append("")
        for i in g.items:
            out.append(f"- **{i.name}** (`{i.id}`)")
            out += _details(i)

    if catalog.known:
        out += ["", '<a id="known"></a>', "## Known, not restored", "",
                "Seen on the machine and understood, but `mi restore` never installs them.", "",
                "| Item | What | Why |", "|---|---|---|"]
        for i in catalog.known:
            what = "; ".join(f"{k}: {', '.join(i.get(k))}" for k in SHOWN if i.get(k)) or "-"
            out.append(f"| `{i.id}` | {_cell(what)} | {_cell(i.why or i.notes) or '-'} |")

    if catalog.apt_sources:
        out += ["", "## apt sources", "", "| Id | File / line | Keyring |", "|---|---|---|"]
        for sid, s in catalog.apt_sources.items():
            src = s.get("file") or s.get("line")
            key = s.get("keyring", "-") + (f" (from {s['key_url']})" if s.get("key_url") else "")
            out.append(f"| `{sid}` | `{_cell(src)}` | {_cell(key)} |")
    return "\n".join(out) + "\n"
